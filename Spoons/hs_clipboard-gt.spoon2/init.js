function pasteOnSelectToggle() {
    pasteOnSelect = !pasteOnSelect
    historySave()
    hs.ui.alert(`Paste-on-select is now ${pasteOnSelect ? "enabled" : "disabled"}`)
        .duration(config.alertDuration).show()
    return pasteOnSelect
}

// MARK: - Revealing masked entries

function revealReset() {
    revealAll = false
    revealedRow = null
}

// ⌘R: reveal the selected row, or hide it again if it is the one already revealed.
function currentPasswordRevealToggle() {
    if (!chooser) return module.exports
    const row = chooser.selectedRow
    if (row === null || row === undefined || row < 0) return module.exports

    revealedRow = revealedRow === row ? null : row
    chooserRefresh()
    chooser.selectedRow = row
    return module.exports
}

// ⇧⌘R: reveal every masked entry, or mask them all again.
function passwordsRevealToggle() {
    if (!chooser) return module.exports
    const row = chooser.selectedRow

    revealAll = !revealAll
    revealedRow = null
    chooserRefresh()
    if (row !== null && row !== undefined && row >= 0) chooser.selectedRow = row
    return module.exports
}

