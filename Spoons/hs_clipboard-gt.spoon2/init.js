// The pasteboard's change count just after this Spoon last wrote to it. Writing an entry back
// is a change like any other, and the watcher would otherwise store it again. The count is
// compared rather than the contents, so a new copy of identical text or of an image of the
// same size is still stored.
let ownChangeCount = null

/** Write to the pasteboard, and remember that the change is this Spoon's own. */
function pasteboardWrite(write) {
    const written = write()
    ownChangeCount = hs.pasteboard.changeCount
    return written
}

// MARK: - Persistence

function historyLoad() {
    if (!hs.fs.exists(config.historyFile)) return

    const body = hs.fs.read(config.historyFile, 0, 0)
    if (!body || body === "") return

    let data = null
    try {
        data = JSON.parse(body)
    } catch (error) {
        console.error(`[hs_clipboard-gt] ${config.historyFile} is unreadable, starting fresh: ${error}`)
        return
    }
    if (!data || typeof data !== "object") return

    pasteOnSelect = data.pasteOnSelect === true
    history = historyPrune(Array.isArray(data.items) ? data.items : [])
}

// Password-like entries live in memory only, so they are dropped on the way out. This
// also scrubs any that an earlier version of the Spoon, or of its v1 ancestor, wrote.
function historySave() {
    const items = config.passwordsHide
        ? history.filter((entry) => entry.type === "image" || !passwordLike(entry.content))
        : history
    hs.fs.write(config.historyFile,
        JSON.stringify({pasteOnSelect: pasteOnSelect, items: items}, null, 2), false)
}

// MARK: - The history itself

// Discards malformed entries, collapses duplicates and applies the size caps. The first
// of a set of duplicates wins, so the most recent copy keeps its place at the top.
//
// Text and images are counted separately: a burst of screenshots would otherwise evict
// the text history, and the two are not interchangeable. Order is preserved across both,
// so the list still reads newest first whatever the entries are.
//
// An image that falls off the end takes its file with it; see imagesSweep().
function historyPrune(list) {
    const result = []
    const seen = new Set()
    let texts = 0
    let images = 0

    for (const entry of list) {
        if (!entry) continue

        if (entry.type === "image") {
            if (images >= config.imageHistorySize) continue
            if (typeof entry.path !== "string" || !hs.fs.exists(entry.path)) continue
            images += 1
            result.push({
                type: "image",
                path: entry.path,
                width: entry.width || 0,
                height: entry.height || 0
            })
            continue
        }

        if (entry.type !== "text" || typeof entry.content !== "string") continue
        if (texts >= config.historySize) continue

        const hash = hs.hashing.md5(entry.content)
        if (config.deduplicate && seen.has(hash)) continue

        seen.add(hash)
        texts += 1
        result.push({type: "text", content: entry.content})
    }
    return result
}

/**
 * Delete the image files in clipboardDir that no entry refers to any more.
 *
 * Called after the history changes, so the directory holds what the history holds and no
 * more. A file that will not go is left for the next sweep.
 *
 * @returns {number} How many files were deleted.
 */
function imagesSweep() {
    const wanted = new Set(history.filter((e) => e.type === "image").map((e) => e.path))
    const names = hs.fs.list(config.clipboardDir) || []
    let removed = 0

    for (const name of names) {
        if (!/\.png$/.test(name)) continue
        const path = `${config.clipboardDir}/${name}`
        if (wanted.has(path)) continue
        if (hs.fs.deletePath(path)) removed += 1
    }
    return removed
}

// Cuts an over-long entry at the last blank line that fits, and failing that at the
// limit itself.
function contentTruncate(text) {
    if (text.length <= config.maxEntrySize) return text

    const paragraph = text.lastIndexOf("\n\n", config.maxEntrySize)
    return paragraph > 0 ? text.slice(0, paragraph) : text.slice(0, config.maxEntrySize)
}

function historyAdd(text) {
    history.unshift({type: "text", content: text})
    history = historyPrune(history)
    historySave()
}

// MARK: - Reading the pasteboard

function pasteboardIgnored() {
    if (!config.honorIgnoredIdentifiers) return false
    return (hs.pasteboard.types() || []).some((type) => config.ignoredIdentifiers.includes(type))
}

/** Whether the pasteboard is offering an image, by type rather than by guessing. */
function pasteboardHasImage() {
    for (const type of ["public.png", "public.tiff", "public.jpeg"]) {
        try {
            if (hs.pasteboard.hasType(type)) return true
        } catch (e) { /* try the next */ }
    }
    return false
}

/**
 * Store the image on the pasteboard as a file, and put an entry at the top of the history.
 *
 * The file is named for the time it was copied, which sorts and reads well in a directory
 * listing. Two copies in the same second are told apart by a number after the second's.
 */
function imageCapture() {
    const image = hs.pasteboard.readImage()
    if (!image) return false

    hs.fs.mkdir(config.clipboardDir)

    const stamp = new Date().toISOString().replace(/[-:]/g, "").replace(/\..+$/, "")
    // A second image copied in the same second is given -2, -3 and so on, so that it does not
    // overwrite the first. The tests found the collision on 2026-11-23.
    let path = `${config.clipboardDir}/${stamp}.png`
    for (let n = 2; hs.fs.exists(path); n++) path = `${config.clipboardDir}/${stamp}-${n}.png`

    if (!image.saveToFile(path)) {
        console.error(`[hs_clipboard-gt] could not write ${path}`)
        return false
    }

    const size = image.size
    history.unshift({
        type: "image",
        path: path,
        width: size ? Math.round(size.w) : 0,
        height: size ? Math.round(size.h) : 0
    })
    history = historyPrune(history)
    historySave()
    imagesSweep()

    if (config.copiedAlert) {
        const dimensions = size ? `${Math.round(size.w)}x${Math.round(size.h)}` : "an image"
        hs.ui.alert(`Copied ${dimensions} image`).duration(config.alertDuration).show()
    }
    return true
}

function pasteboardCapture() {
    // This Spoon's own write, of an entry selected in the chooser: nothing was copied, so
    // there is nothing to store or announce.
    if (ownChangeCount !== null && hs.pasteboard.changeCount === ownChangeCount) return
    if (pasteboardIgnored()) return

    if (pasteboardHasImage()) {
        imageCapture()
        return
    }

    const content = hs.pasteboard.readString()
    if (content === null || content === undefined || content === "") return

    // Selecting an entry writes it back to the pasteboard, which arrives here as a
    // change of its own. Nothing has been copied, so there is nothing to announce.
    if (history.length > 0 && history[0].content === content) return

    const stored = contentTruncate(content)
    historyAdd(stored)

    if (!config.copiedAlert) return
    const masked = config.passwordsHide && passwordLike(stored)
    const note = masked ? " (password-like, not persisted)" : ""
    const shortened = stored.length < content.length ? ` of ${content.length}` : ""
    hs.ui.alert(`Copied ${stored.length}${shortened} chars${note}`).duration(config.alertDuration).show()
}

// MARK: - Typing and pasting

// The chooser holds focus while it is up, so anything typed has to wait for the window
// underneath to have it back.
function windowRestore(then) {
    if (chooser && chooser.isVisible) chooser.hide()
    if (previousWindow) previousWindow.focus()
    hs.timer.doAfter(config.pasteDelay, then)
}

// v1's "paste all with delimiter": every entry from the given row up to the newest one,
// typed out oldest first, each followed by the delimiter.
function entriesPaste(row, delimiter) {
    const entries = history.slice(0, row + 1).reverse()
    windowRestore(() => {
        for (const entry of entries) {
            // An image cannot be typed, so it is passed over rather than stopping the run.
            if (entry.type === "image") continue
            hs.eventtap.keyStrokes(entry.content)
            hs.eventtap.keyStrokes(delimiter)
        }
    })
}

// MARK: - Rearranging entries

function entryDelete(row) {
    if (row < 0 || row >= history.length) return module.exports
    history.splice(row, 1)
    historySave()
    imagesSweep()
    chooserRefresh()
    return module.exports
}

function entryMove(row, destination) {
    if (row < 0 || row >= history.length) return module.exports
    const target = Math.min(Math.max(destination, 0), history.length - 1)
    if (target === row) return module.exports

    const [entry] = history.splice(row, 1)
    history.splice(target, 0, entry)
    historySave()
    chooserRefresh()
    return module.exports
}

function entryToTopMove(row) { return entryMove(row, 0) }
function entryUpMove(row) { return entryMove(row, row - 1) }
function entryDownMove(row) { return entryMove(row, row + 1) }

// Reverses the order of everything from the newest entry down to the given row, which is
// what v1 offered for turning a set of copies back into the order they were made in.
function entriesInvert(row) {
    if (row < 0 || row >= history.length) return module.exports
    const head = history.slice(0, row + 1).reverse()
    history = head.concat(history.slice(row + 1))
    historySave()
    chooserRefresh()
    return module.exports
}

function historyClear() {
    hs.pasteboard.clear()
    history = []
    historySave()
    imagesSweep()
    chooserRefresh()
    return module.exports
}

function historyLastDelete() {
    return entryDelete(0)
}

