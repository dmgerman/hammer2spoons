// MARK: - The preview
//
// The selected image, drawn on a canvas to the left of the chooser. A row's own image is a
// few points high, which distinguishes two screenshots but does not let you read either.
//
// The same approach as the window preview in hs_selectWindow-gt, and the second use of it.
// If a third appears it is worth extracting: the sizing, the placement and the polling are
// not specific to what the picture is of.

const HAMMERSPOON_BUNDLE_ID = "net.tenshu.Hammerspoon-2"

/**
 * Where the chooser is, so the preview can sit beside it.
 *
 * Its width and left edge follow from hs.chooser centring a window of the configured
 * width. Its vertical position does not, and hs.chooser reports no frame, so it is read
 * from Hammerspoon's own window list: the chooser is the window whose left edge and width
 * match the computed ones, which separates it from the console and from this canvas.
 *
 * Asking one application for its windows costs about 10ms.
 */
function chooserGeometry(area) {
    const width = area.w * (chooser && chooser.width ? chooser.width : 0.5)
    const left = area.x + (area.w - width) / 2
    let top = area.y + area.h * config.previewTopRatio

    try {
        const app = hs.application.matchingBundleID(HAMMERSPOON_BUNDLE_ID)
        for (const window of (app ? app.allWindows || [] : [])) {
            const frame = window.frame
            if (!frame) continue
            if (Math.abs(frame.x - left) <= 2 && Math.abs(frame.w - width) <= 2) {
                top = frame.y
                break
            }
        }
    } catch (e) {
        // The computed position stands.
    }

    return { left: left, width: width, top: top }
}

/** Where to draw a preview of this image, or null when there is nowhere sensible. */
function previewFrame(image) {
    const screen = hs.screen.main() || hs.screen.primary()
    const reference = hs.screen.primary() || screen
    if (!screen || !reference) return null

    const area = screen.frame
    const size = image.size
    if (!size || !size.w || !size.h) return null

    // A maximum rather than a target: a small image drawn at four times its size is a
    // blurred rectangle, and says less than the same image drawn honestly.
    let height = Math.min(area.h * config.previewHeightRatio, size.h)
    let width = size.w * (height / size.h)

    const geometry = chooserGeometry(area)
    const available = (geometry.left - area.x) - config.previewGap * 2
    if (available > 0 && width > available) {
        height = height * (available / width)
        width = available
    }

    const left = geometry.left - config.previewGap - width
    const top = geometry.top

    // hs.screen measures y downwards from the top of the primary display and a canvas
    // upwards from its bottom.
    return {
        x: left,
        y: (reference.fullFrame.y + reference.fullFrame.h) - (top + height),
        w: width,
        h: height
    }
}

function previewHide() {
    if (!preview) return
    preview.destroy()
    preview = null
    previewRow = null
}

function previewDraw(image, row) {
    previewHide()
    if (!image) return

    const frame = previewFrame(image)
    if (!frame) return

    preview = hs.canvas.create(frame)
        .level("popUpMenu")
        .ignoreMouseEvents(true)
        .behaviorList(["canJoinAllSpaces", "stationary"])

    preview.appendElements([
        {
            type: "rectangle",
            action: "fill",
            fillColor: { red: 0, green: 0, blue: 0, alpha: 0.55 },
            frame: { x: 0, y: 0, w: frame.w, h: frame.h },
            roundedRectRadii: { xRadius: 10, yRadius: 10 }
        },
        {
            type: "image",
            image: image,
            frame: { x: 4, y: 4, w: frame.w - 8, h: frame.h - 8 },
            imageScaling: "scaleProportionally",
            imageAlignment: "center"
        }
    ])
    preview.show()
    previewRow = row
}

/** The history row the chooser has selected, or null. */
function selectedRow() {
    if (!chooser || !chooser.isVisible) return null
    const contents = chooser.selectedRowContents(chooser.selectedRow)
    return contents && contents.row !== undefined ? contents.row : null
}

/** Draw, redraw or take away the preview, according to what is selected now. */
function previewUpdate() {
    if (!config.showPreview) return
    if (!chooser || !chooser.isVisible) {
        previewHide()
        return
    }

    const row = selectedRow()
    if (row === null) {
        previewHide()
        return
    }
    if (row === previewRow) return

    const entry = history[row]
    if (!entry || entry.type !== "image") {
        previewHide()
        return
    }

    const image = HSImage.fromPath(entry.path)
    if (!image) {
        previewHide()
        return
    }
    previewDraw(image, row)
}

function previewPollStart() {
    previewPollStop()
    if (!config.showPreview) return
    previewTimer = hs.timer.doEvery(config.previewPollSeconds, () => previewUpdate())
}

function previewPollStop() {
    if (!previewTimer) return
    previewTimer.stop()
    previewTimer = null
}

// MARK: - The chooser

// Right-clicking an entry offers what v1 put behind its own context menu. The chooser holds
// one menu for every row and passes the right-clicked choice to contextMenuSelect(), whose
// row field says which entry to act on. The control rows opt out with contextMenu: false.
const CONTEXT_MENU = [
    {title: "Paste all up to here, tab separated", id: "pasteTabs"},
    {title: "Paste all up to here, one per line", id: "pasteLines"},
    {type: "divider"},
    {title: "Delete entry", id: "delete"},
    {title: "Move entry to top", id: "moveToTop"},
    {title: "Move entry up", id: "moveUp"},
    {title: "Move entry down", id: "moveDown"},
    {title: "Invert order above", id: "invert"}
]

const CONTEXT_MENU_ACTIONS = {
    pasteTabs: (row) => entriesPaste(row, "\t"),
    pasteLines: (row) => entriesPaste(row, "\n"),
    delete: (row) => entryDelete(row),
    moveToTop: (row) => entryToTopMove(row),
    moveUp: (row) => entryUpMove(row),
    moveDown: (row) => entryDownMove(row),
    invert: (row) => entriesInvert(row)
}

function contextMenuSelect(choice, menuItem) {
    const action = CONTEXT_MENU_ACTIONS[menuItem.id]
    if (!action || typeof choice.row !== "number") return
    action(choice.row)
}

function chooserChoices() {
    const choices = []

    history.forEach((entry, row) => {
        if (entry.type === "image") {
            // The picture itself is the row's image, so the entry is recognisable without
            // reading anything. The chooser scales it to the row.
            choices.push({
                text: `${entry.width}x${entry.height} image`,
                subText: entry.path.split("/").pop(),
                image: HSImage.fromPath(entry.path),
                action: "pasteImage",
                data: entry.path,
                row: row
            })
            return
        }

        const masked = config.passwordsHide && passwordLike(entry.content)
        const revealed = revealAll || revealedRow === row
        const text = (masked && !revealed)
            ? `[hidden - ${entry.content.length} chars]`
            : entry.content.slice(0, config.displayMaxLength)

        choices.push({
            text: text,
            action: "paste",
            data: entry.content,
            row: row
        })
    })

    if (choices.length === 0) {
        choices.push({
            text: "",
            subText: "《Clipboard is empty》",
            action: "none",
            image: HSImage.fromName("NSCaution"),
            contextMenu: false
        })
    } else {
        choices.push({
            text: "《Clear Clipboard History》",
            action: "clear",
            image: HSImage.fromName("NSTrashFull"),
            contextMenu: false
        })
    }

    choices.push({
        text: `《${pasteOnSelect ? "Disable" : "Enable"} Paste-on-select》`,
        action: "pasteOnSelect",
        // v1 used NSSwitchEnabledOn/Off, which this macOS no longer resolves.
        image: HSImage.fromSymbol(pasteOnSelect ? "checkmark.circle.fill" : "circle"),
        contextMenu: false
    })

    return choices
}

function chooserRefresh() {
    if (chooser) chooser.setChoices(chooserChoices())
    return module.exports
}

function chooserSelect(choice) {
    revealKeysDisable()
    revealReset()

    if (!choice) return

    if (choice.action === "clear") {
        historyClear()
        return
    }
    if (choice.action === "pasteOnSelect") {
        pasteOnSelectToggle()
        chooserRefresh()
        return
    }
    previewPollStop()
    previewHide()

    if (choice.action === "pasteImage" && typeof choice.data === "string") {
        const image = HSImage.fromPath(choice.data)
        if (!image) {
            hs.ui.alert("That image is no longer on disk").duration(2).show()
            return
        }
        pasteboardWrite(() => hs.pasteboard.writeImage(image))
        if (previousWindow) previousWindow.focus()
        if (pasteOnSelect) {
            hs.timer.doAfter(config.pasteDelay, () => hs.eventtap.keyStroke(["cmd"], "v"))
        }
        return
    }

    if (choice.action !== "paste" || typeof choice.data !== "string") return

    pasteboardWrite(() => hs.pasteboard.writeString(choice.data))
    if (previousWindow) previousWindow.focus()
    if (pasteOnSelect) {
        hs.timer.doAfter(config.pasteDelay, () => hs.eventtap.keyStroke(["cmd"], "v"))
    }
}

// MARK: - Lifecycle

function start() {
    if (chooser) return module.exports

    // Both are required. Checked here, so that a missing one is reported when the Spoon
    // starts rather than the first time it is needed.
    spoonRequired("hs_interactive-gt")
    spoonRequired("hs_menu-gt")

    hs.fs.mkdir(config.clipboardDir)
    historyLoad()
    // Rewrite at once, so that anything password-like left on disk by an earlier run is
    // scrubbed whether or not something is copied this session.
    historySave()

    chooser = hs.chooser.create()
    chooser.placeholder = "Clipboard history"
    chooser.onSelect = chooserSelect
    chooser.contextMenu = CONTEXT_MENU
    chooser.onContextMenuSelect = contextMenuSelect
    chooser.onShow = () => {
        revealKeysEnable()
        previewPollStart()
    }
    chooser.onHide = () => {
        promptRelease()
        revealKeysDisable()
        revealReset()
        previewPollStop()
        previewHide()
        // Rebuild at once, so a revealed entry is not left in the chooser's own list.
        chooserRefresh()
    }
    chooser.setChoices(chooserChoices())

    revealCurrentHotkey = hs.hotkey.create(config.revealCurrentKey.mods, config.revealCurrentKey.key,
        () => currentPasswordRevealToggle(), null)
    revealAllHotkey = hs.hotkey.create(config.revealAllKey.mods, config.revealAllKey.key,
        () => passwordsRevealToggle(), null)

    hs.pasteboard.watcherInterval = config.watchInterval
    watcher = () => pasteboardCapture()
    hs.pasteboard.on("change", watcher)

    if (config.menubarShow) {
        menubarItem = hs.menubar.create(false)
        menubarItem.title = config.menubarTitle
        menubarItem.setClickCallback(() => historyToggle())
    }

    return module.exports
}

function stop() {
    hotkeysRelease()
    previewPollStop()
    previewHide()
    if (watcher) {
        hs.pasteboard.off("change", watcher)
        watcher = null
    }
    if (chooser) {
        chooser.hide()
        chooser = null
    }
    promptRelease()
    if (revealCurrentHotkey) {
        revealCurrentHotkey.destroy()
        revealCurrentHotkey = null
    }
    if (revealAllHotkey) {
        revealAllHotkey.destroy()
        revealAllHotkey = null
    }
    if (menubarItem) {
        menubarItem.destroy()
        menubarItem = null
    }
    revealReset()
    return module.exports
}

function historyShow() {
    if (!chooser) {
        console.error("[hs_clipboard-gt] historyShow() before start()")
        return module.exports
    }
    previousWindow = hs.window.focusedWindow()
    chooserRefresh()
    // Reported as a prompt of hs_interactive-gt, so that promptIsOpen() is true while the
    // history is open and hs_menu-gt releases its letters. The chooser's onHide reports the
    // close.
    if (!promptHeld) {
        spoonRequired("hs_interactive-gt").promptOpened()
        promptHeld = true
    }
    chooser.show()
    return module.exports
}

/** Report the close of the history's chooser to hs_interactive-gt, once. */
function promptRelease() {
    if (!promptHeld) return
    promptHeld = false
    const interactive = hs.spoons["hs_interactive-gt"]
    if (interactive) interactive.promptClosed()
}

function historyHide() {
    if (chooser) chooser.hide()
    return module.exports
}

function historyToggle() {
    if (!chooser) return historyShow()
    return chooser.isVisible ? historyHide() : historyShow()
}

// Reading accessors, for commands and for the console.
function historyEntries() {
    return history.map((entry) => entry.type === "image"
        ? `[image ${entry.width}x${entry.height}] ${entry.path}`
        : entry.content)
}

function pasteOnSelectIsEnabled() {
    return pasteOnSelect
}

